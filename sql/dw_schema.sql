-- ============================================================================
-- Data Warehouse (star constellation) · Workshop §6.4 / §6.10
-- Design and rationale: README §9
--
--   Facts   : fact_track_artist (DW-F1)   fact_grammy_award (DW-F2)
--   Bridges : bridge_artist_genre (DW-B1) bridge_award_track (DW-B2)
--   Dims    : dim_artist dim_track dim_genre dim_category dim_year
--   Audit   : etl_load_audit (one row per committed load; not an analytical table)
--
-- Idempotent (IF NOT EXISTS / ON CONFLICT): applying it twice changes nothing. src/load.py runs it at the start of
-- every load, inside the load transaction.
-- Surrogate keys for free-text dimensions, each with a UNIQUE business key; the primary key of every fact is its
-- grain, so a duplicated grain row is physically impossible. CHECK constraints repeat the invariants that
-- validate_prepared verifies before the load (second line of defence).
-- ============================================================================

-- ---------------------------------------------------------------- dimensions
CREATE TABLE IF NOT EXISTS dim_artist (
    artist_key        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_norm       TEXT    NOT NULL UNIQUE,                 -- business key = integration key
    artist_name       TEXT    NOT NULL,
    in_spotify        BOOLEAN NOT NULL,
    is_grammy_winner  BOOLEAN NOT NULL,
    grammy_win_count  INTEGER NOT NULL DEFAULT 0 CHECK (grammy_win_count >= 0),
    first_grammy_year INTEGER,
    CONSTRAINT ck_dim_artist_flag CHECK (is_grammy_winner = (grammy_win_count > 0))
);

CREATE TABLE IF NOT EXISTS dim_track (
    track_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id    CHAR(22) NOT NULL UNIQUE,                      -- business key (Spotify id)
    track_name  TEXT     NOT NULL,
    album_name  TEXT     NOT NULL,
    explicit    BOOLEAN
);

CREATE TABLE IF NOT EXISTS dim_genre (
    genre_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name  TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dim_category (
    category_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_norm  TEXT NOT NULL UNIQUE,                       -- lower, trimmed, single-spaced
    category_name  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_year (
    year_key        INTEGER PRIMARY KEY CHECK (year_key BETWEEN 1958 AND 2100),   -- smart key = the Grammy year label
    decade          INTEGER NOT NULL,
    ceremony_no     INTEGER,
    ceremony_title  TEXT,
    CONSTRAINT ck_dim_year_decade CHECK (decade = (year_key / 10) * 10)
);

-- Unknown member: Grammy rows without artist keep a valid foreign key (so the match rate has a denominator).
INSERT INTO dim_artist (artist_key, artist_norm, artist_name, in_spotify, is_grammy_winner, grammy_win_count)
OVERRIDING SYSTEM VALUE
VALUES (0, '(no artist)', '(no artist in source)', FALSE, FALSE, 0)
ON CONFLICT (artist_key) DO NOTHING;

-- ---------------------------------------------------------------- facts
CREATE TABLE IF NOT EXISTS fact_track_artist (
    track_key          INTEGER  NOT NULL REFERENCES dim_track  (track_key),
    artist_key         INTEGER  NOT NULL REFERENCES dim_artist (artist_key),
    artist_position    SMALLINT NOT NULL CHECK (artist_position >= 1),
    is_primary_artist  BOOLEAN  NOT NULL,
    popularity         NUMERIC(5,2) NOT NULL CHECK (popularity BETWEEN 0 AND 100),   -- mean across genre listings
    is_high_popularity SMALLINT NOT NULL CHECK (is_high_popularity IN (0, 1)),
    danceability       REAL CHECK (danceability BETWEEN 0 AND 1),
    energy             REAL CHECK (energy BETWEEN 0 AND 1),
    valence            REAL CHECK (valence BETWEEN 0 AND 1),
    loudness_db        REAL,
    tempo_bpm          REAL CHECK (tempo_bpm > 0),              -- NULL when the source placeholder 0 was found
    duration_ms        INTEGER CHECK (duration_ms > 0),
    PRIMARY KEY (track_key, artist_key),                         -- the grain
    CONSTRAINT ck_primary_is_position_1 CHECK (is_primary_artist = (artist_position = 1))
);

CREATE TABLE IF NOT EXISTS fact_grammy_award (
    grammy_row_id       INTEGER PRIMARY KEY,                     -- the grain: one award entry of the source table
    year_key            INTEGER NOT NULL REFERENCES dim_year     (year_key),
    category_key        INTEGER NOT NULL REFERENCES dim_category (category_key),
    artist_key          INTEGER NOT NULL REFERENCES dim_artist   (artist_key),
    nominee             TEXT,
    win_count           SMALLINT NOT NULL CHECK (win_count = 1),
    is_matchable        BOOLEAN  NOT NULL,
    is_track_matched    BOOLEAN  NOT NULL,
    matched_track_count INTEGER  NOT NULL CHECK (matched_track_count >= 0),
    CONSTRAINT ck_match_flag    CHECK (is_track_matched = (matched_track_count > 0)),
    CONSTRAINT ck_match_implies CHECK (NOT is_track_matched OR is_matchable)
);

-- ---------------------------------------------------------------- bridges
CREATE TABLE IF NOT EXISTS bridge_artist_genre (
    artist_key   INTEGER NOT NULL REFERENCES dim_artist (artist_key),
    genre_key    INTEGER NOT NULL REFERENCES dim_genre  (genre_key),
    track_count  INTEGER NOT NULL CHECK (track_count >= 1),
    PRIMARY KEY (artist_key, genre_key)
);

CREATE TABLE IF NOT EXISTS bridge_award_track (
    grammy_row_id  INTEGER NOT NULL REFERENCES fact_grammy_award (grammy_row_id),
    track_key      INTEGER NOT NULL REFERENCES dim_track (track_key),
    match_type     TEXT    NOT NULL CHECK (match_type IN ('track_name', 'album_name')),
    PRIMARY KEY (grammy_row_id, track_key)
);

-- Join paths used by the KPI queries
CREATE INDEX IF NOT EXISTS ix_fta_artist  ON fact_track_artist (artist_key);
CREATE INDEX IF NOT EXISTS ix_fga_year    ON fact_grammy_award (year_key);
CREATE INDEX IF NOT EXISTS ix_fga_artist  ON fact_grammy_award (artist_key);
CREATE INDEX IF NOT EXISTS ix_bat_track   ON bridge_award_track (track_key);
CREATE INDEX IF NOT EXISTS ix_bag_genre   ON bridge_artist_genre (genre_key);

-- ---------------------------------------------------------------- load audit (§6.11 logging, §7.3 rerun evidence)
CREATE TABLE IF NOT EXISTS etl_load_audit (
    load_id      INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch_id     TEXT        NOT NULL,
    dag_run_id   TEXT,
    started_at   TIMESTAMPTZ NOT NULL,
    finished_at  TIMESTAMPTZ NOT NULL,
    rows_loaded  JSONB       NOT NULL,      -- row count of every DW table after the load
    measures     JSONB       NOT NULL,      -- selected measures (avg popularity, total wins, matched rows, winners)
    changes      JSONB       NOT NULL       -- per table: updated / inserted / deleted_stale
);
